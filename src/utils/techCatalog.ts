// ───────────────────────────── Lookups ─────────────────────────────

export const TECH_BY_SLUG: ReadonlyMap<string, TechDef> = new Map(
  TECH_CATALOG.map((tech) => [tech.slug, tech]),
);

const ALIAS_EXACT = new Map<string, string>();
const ALIAS_LOOSE = new Map<string, string>();

function registerAlias(name: string, slug: string): void {
  const lower = name.trim().toLowerCase();

  if (!lower) {
    return;
  }

  if (!ALIAS_EXACT.has(lower)) {
    ALIAS_EXACT.set(lower, slug);
  }

  // "next.js" / "vue-router" style names also resolve without punctuation,
  // but never for names where punctuation is meaningful (c#, c++).
  const loose = lower.replace(/[^a-z0-9]/g, '');

  if (loose && !/[#+]/.test(lower) && !ALIAS_LOOSE.has(loose)) {
    ALIAS_LOOSE.set(loose, slug);
  }
}

TECH_CATALOG.forEach((tech) => {
  registerAlias(tech.slug, tech.slug);
  registerAlias(tech.label, tech.slug);
  tech.aliases?.forEach((alias) => registerAlias(alias, tech.slug));
});

/** Normalises any tech name/alias/slug ("Next.js", "ts", "c++") to its canonical slug. */
export function resolveTechSlug(raw: string): string {
  const lower = raw.trim().toLowerCase();

  if (!lower) {
    return '';
  }

  const exact = ALIAS_EXACT.get(lower);

  if (exact) {
    return exact;
  }

  const loose = lower.replace(/[^a-z0-9]/g, '');
  return ALIAS_LOOSE.get(loose) ?? loose;
}

export function getTechDef(tech: string): TechDef | undefined {
  return TECH_BY_SLUG.get(resolveTechSlug(tech));
}

export function isLanguageSlug(tech: string): boolean {
  return getTechDef(tech)?.kind === 'language';
}
