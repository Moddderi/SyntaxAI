/**
 * Single source of truth for every technology SyntaxAI can recognise:
 * slug, label, brand color, Devicon icon, aliases and detection signals.
 *
 * Detection (see techDetection.ts) scores each entry against the captured text:
 *   strong = unmistakable (an import, a unique API)           -> 10
 *   medium = typical but shared with other stacks              ->  5
 *   weak   = hint only                                         ->  2
 *   domains (page URL)                                         -> 12
 * A framework/library/tool needs >= 10 to become the primary technology.
 */

export type TechKind =
  | 'language'
  | 'framework'
  | 'library'
  | 'utility'
  | 'tool'
  | 'database'
  | 'platform';

export interface TechDef {
  /** Canonical slug (matches the Devicon folder name whenever possible). */
  slug: string;
  label: string;
  kind: TechKind;
  color: string;
  /** Short text shown when no icon is available (max 3 chars). */
  abbr?: string;
  /** Extra names that resolve to this slug (lowercase). */
  aliases?: string[];
  /** Devicon folder if it differs from `slug`. */
  icon?: string;
  /** Custom icon URLs tried before Devicon. */
  iconUrls?: string[];
  /** Language this stack is written in. */
  base?: string;
  /** Stacks this one is built on: when both match, this one wins. */
  implies?: string[];
  /** URL hosts/paths that identify docs for this tech (strong). */
  domains?: string[];
  /** URL hosts that only weakly suggest it (e.g. MDN). */
  weakDomains?: string[];
  /** Regex sources for prose mentions (case-insensitive, matched in title/body/url). */
  mentions?: string[];
  strong?: RegExp[];
  medium?: RegExp[];
  weak?: RegExp[];
  /** Extra scorer for signals a plain regex cannot express. */
  custom?: (text: string) => number;
}

/** Tailwind utility classes are too varied for one regex: count utility-like tokens per class attribute. */
const TAILWIND_TOKEN =
  /^(?:[a-z0-9-]+:)*-?(?:(?:p|m|px|py|pt|pb|pl|pr|mx|my|mt|mb|ml|mr|w|h|gap|space-x|space-y|top|left|right|bottom|inset|z|min-w|max-w|min-h|max-h|size|leading|tracking|opacity|rotate|scale|translate-x|translate-y|grid-cols|col-span|row-span|order)-[\w./[\]%#-]+|flex|grid|block|hidden|inline|inline-flex|inline-block|contents|items-[\w-]+|justify-[\w-]+|self-[\w-]+|rounded(?:-[\w-]+)?|text-[\w/[\]#-]+|bg-[\w/[\]#-]+|border(?:-[\w/[\]#-]+)?|font-[\w-]+|shadow(?:-[\w-]+)?|ring(?:-[\w-]+)?|transition(?:-[\w-]+)?|duration-\d+|ease-[\w-]+|overflow-[\w-]+|cursor-[\w-]+|truncate|underline|uppercase|lowercase|capitalize|relative|absolute|fixed|sticky|static|antialiased|sr-only|container|mx-auto|animate-[\w-]+|object-[\w-]+|whitespace-[\w-]+|break-[\w-]+|flex-[\w-]+|fill-[\w-]+|stroke-[\w-]+)$/;

function tailwindScore(text: string): number {
  const attributePattern = /\bclass(?:Name)?\s*=\s*(?:"([^"\n]{3,400})"|'([^'\n]{3,400})'|\{\s*`([^`\n]{3,400})`)/g;
  let best = 0;
  let seen = 0;
  let match: RegExpExecArray | null = attributePattern.exec(text);

  while (match && seen < 25) {
    const value = match[1] ?? match[2] ?? match[3] ?? '';
    const hits = value.split(/\s+/).filter((token) => TAILWIND_TOKEN.test(token)).length;
    best = Math.max(best, hits);
    seen += 1;
    match = attributePattern.exec(text);
  }

  if (best >= 4) return 12;
  if (best >= 3) return 9;
  if (best >= 2) return 4;
  return 0;
}

