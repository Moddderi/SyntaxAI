#!/usr/bin/env node
/**
 * Generates src/utils/deviconIndex.ts: for every Devicon icon, which SVG variant to load.
 * Lets TechIcon request the right file the first time (no 404 guessing) and skip unknown slugs.
 *
 * Run: npm run icons:devicon
 */
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://cdn.jsdelivr.net/gh/devicons/devicon@latest/devicon.json';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'utils', 'deviconIndex.ts');
const PREFERENCE = ['original', 'plain', 'original-wordmark', 'plain-wordmark', 'line', 'line-wordmark'];

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`Failed to fetch devicon.json: ${response.status}`);
}

const icons = await response.json();
const entries = icons
  .map((icon) => {
    const versions = icon.versions?.svg ?? [];
    const variant = PREFERENCE.find((candidate) => versions.includes(candidate)) ?? versions[0];
    return variant ? [icon.name, variant] : null;
  })
  .filter(Boolean)
  .sort((a, b) => a[0].localeCompare(b[0]));

const body = entries.map(([name, variant]) => `  '${name}': '${variant}',`).join('\n');

await writeFile(
  OUT,
  `// AUTO-GENERATED by scripts/generate-devicon-index.mjs — do not edit by hand.
// ${entries.length} icons from devicons/devicon.

/** Devicon icon name -> preferred SVG variant that exists for it. */
export const DEVICON_VARIANTS: Readonly<Record<string, string>> = {
${body}
};
`,
);

console.log(`Wrote ${entries.length} icons to ${OUT}`);
